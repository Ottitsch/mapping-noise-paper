"""Render results/analysis/summary.json, curves.csv, the MFP baseline and the reproduction runs as
Markdown tables for RESULTS.md (written between the GRID markers). Usage: python3 -I results_md.py"""
import glob
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

R = Path(__file__).resolve().parents[2]
A = R / "results" / "analysis"


def f(x, d=3):
    if isinstance(x, float) and np.isinf(x):
        return "beyond the grid"
    return "" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{d}f}"


def main():
    res = json.loads((A / "summary.json").read_text())
    out = ["<!-- GRID START (generated by src/analysis/results_md.py; do not edit by hand) -->", ""]
    out.append("Per split quantities: mean over splits, sd over splits, 95 percent t interval over splits, the same interval with the Nadeau and Bengio correction for overlapping random splits (variance times 1 + J n_test/n_train, n_test/n_train = 0.125; this is the primary interval), hierarchical bootstrap interval (splits then test reactions, 2,000 resamples, own seed per quantity; too narrow with three splits, never quoted alone), p value of the corrected t test against zero, Holm adjusted p value within the headline family of the dataset (secants, H1 difference, RQ3 differences, the H2, H4 and H5 criterion rows, RXNMapper gaps, the RQ5 decomposition and log ratio). Rows without a p value are levels, shares, crossovers or predictions, not differences. Criterion rows subtract the hypothesis threshold, so their interval is read against zero. Three corruption draws per condition everywhere (the realised fractions on the x axis are computed for draws 0 to 2, and levels above 0.10 have three draws), so x and MAE are paired by draw. Source: `results/analysis/summary.json`, produced by `python3 -I src/analysis/analyse.py`. Quantities with no finished runs yet are omitted.")
    for ds in ("rdb7", "e2sn2", "cyclo"):
        rows = [r for r in res if r["dataset"] == ds and (r.get("n_splits", 0) > 0 or r.get("n_beyond_grid"))]
        if not rows:
            continue
        out += ["", f"### {ds}", "", "| quantity | unit | splits | mean | sd | t interval | corrected t interval | bootstrap interval | p (corrected) | p Holm |", "|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            ct = r.get("ci_t")
            cb = r.get("ci_boot")
            cn = r.get("ci_nb")
            notes = []
            if r.get("n_with_curve"):
                if r.get("n_beyond_grid"):
                    notes.append(f"beyond the grid on {r['n_beyond_grid']} of {r['n_with_curve']} splits")
                if r.get("n_undefined"):
                    notes.append(f"undefined on {r['n_undefined']} of {r['n_with_curve']} splits, clean model not better than the reference")
                if r.get("n_recross"):
                    notes.append(f"curve falls below the reference again on {r['n_recross']} of {r['n_with_curve']} splits")
                if notes:
                    notes.append("mean over the defined, finite splits")
            if r.get("note"):
                notes.append(r["note"])
            q = r['quantity'] + (f" ({'; '.join(notes)})" if notes else "")
            out.append(f"| {q} | {r['unit']} | {r['n_splits']} | {f(r.get('mean'))} | {f(r.get('sd'))} | "
                       f"{'' if not ct else f(ct[0]) + ' to ' + f(ct[1])} | {'' if not cn else f(cn[0]) + ' to ' + f(cn[1])} | {'' if not cb else f(cb[0]) + ' to ' + f(cb[1])} | "
                       f"{'' if r.get('p_nb') is None else f'{r['p_nb']:.2g}'} | {'' if r.get('p_holm') is None else f'{r['p_holm']:.2g}'} |")
    c = pd.read_csv(A / "curves.csv")
    out += ["", "### Dose response curves (mean MAE increase over clean, kcal/mol)", "", "Source: `results/analysis/curves.csv`. x is the realised effective fraction of heavy atoms with a wrong partner, averaged over splits.", "",
            "| dataset | regime | level | x effective | MAE increase | sd | splits | MAE |", "|---|---|---|---|---|---|---|---|"]
    for r in c.sort_values(["dataset", "regime", "level"]).itertuples():
        out.append(f"| {r.dataset} | {r.regime} | {r.level:g} | {f(r.x_effective)} | {f(r.delta)} | {f(r.sd)} | {r.n} | {f(r.mae)} |")
    m = []
    for p in sorted(glob.glob(str(R / "results" / "baseline_mfp" / "*.json"))):
        m.append(json.loads(Path(p).read_text()))
    if m:
        m = pd.DataFrame(m).groupby(["dataset", "features"]).agg(n=("mae", "size"), mae=("mae", "mean"), sd=("mae", "std"), rmse=("rmse", "mean")).reset_index()
        out += ["", "### Map free Morgan baseline (gradient boosting)", "", "Source: `results/baseline_mfp/<ds>_<features>_s<k>.json`, produced by `bash src/baseline_mfp/run.sh`.", "",
                "| dataset | features | splits | MAE | sd | RMSE |", "|---|---|---|---|---|---|"]
        for r in m.itertuples():
            out.append(f"| {r.dataset} | {r.features} | {r.n} | {f(r.mae)} | {f(r.sd)} | {f(r.rmse)} |")
    rp = []
    for p in sorted(glob.glob(str(R / "results" / "repro" / "rdb7_explicit_s*" / "test_metrics.csv"))):
        t = pd.read_csv(p)
        rp.append((Path(p).parent.name, float(t.mae.iloc[0])))
    if rp:
        out += ["", "### RDB7 explicit H runs (gate against the Reply)", "", "| run | MAE |", "|---|---|"] + [f"| {a} | {f(b)} |" for a, b in rp]
    for ds in ("rdb7", "e2sn2", "cyclo"):
        p = R / "results" / "operator" / f"{ds}_footprint.csv"
        if p.exists():
            t = pd.read_csv(p)
            out += ["", f"### CGR footprint per touched reaction, {ds}, split 0 test set", "", f"Source: `results/operator/{ds}_footprint.csv`.", "",
                    "| condition | reactions touched | changed CGR atom rows | changed CGR edges |", "|---|---|---|---|"]
            out += [f"| {r.cond} | {r.reactions_touched} | {f(r.changed_rows_per_reaction, 2)} | {f(r.changed_edges_per_reaction, 2)} |" for r in t.itertuples()]
    p = A / "pair_mediator_summary.csv"
    if p.exists():
        t = pd.read_csv(p)
        out += ["", "### RQ3 mediator: CGR features changed by one swap, every split with a clean model", "", "Source: `results/analysis/pair_mediator_summary.csv`, produced by `python3 -I src/analysis/pair_mediator.py` (the exact test swaps of the clean models, eligible reactions).", "",
                "| dataset | swap | splits | CGR atom rows changed | sd | CGR edges changed | sd | share of swaps that change no CGR feature |", "|---|---|---|---|---|---|---|---|"]
        out += [f"| {r.dataset} | {r.kind} | {r.splits} | {f(r.rows, 2)} | {f(r.rows_sd, 2)} | {f(r.edges, 2)} | {f(r.edges_sd, 2)} | {f(r.unchanged, 3)} |" for r in t.itertuples()]
    fr = []
    for ds in ("rdb7", "e2sn2", "cyclo"):
        p = R / "results" / "operator" / f"{ds}_fractions.csv"
        if p.exists():
            t = pd.read_csv(p)
            x = R / "results" / "operator" / f"{ds}_fractions_extra.csv"
            if x.exists():
                t = pd.concat([t, pd.read_csv(x)], ignore_index=True)
            t = t[t.part == "test"].groupby("cond")[["nominal", "effective", "reactions_touched"]].mean()
            fr += [f"| {ds} | {c} | {f(r.nominal)} | {f(r.effective)} | {f(r.reactions_touched)} |" for c, r in t.iterrows()]
    if fr:
        out += ["", "### Realised corruption on the test sets (mean over splits and draws)", "", "Source: `results/operator/<ds>_fractions.csv` (`bash src/analysis/run_operator.sh`) and `results/operator/rdb7_fractions_extra.csv` (`python3 -I src/analysis/operator_extra.py`). Nominal: heavy atoms with a wrong partner; effective: those whose CGR atom row or an incident CGR edge changes; reactions touched: share of test reactions with at least one wrong atom.", "",
                "| dataset | condition | nominal | effective | reactions touched |", "|---|---|---|---|---|"] + fr
    out += ["", "<!-- GRID END -->"]
    md = (R / "RESULTS.md").read_text()
    block = "\n".join(out)
    if "<!-- GRID START" in md:
        md = re.sub(r"<!-- GRID START.*<!-- GRID END -->", lambda _: block, md, flags=re.S)
    else:
        md = md.replace("Filled from `results/analysis/summary.json` (`python3 -I src/analysis/analyse.py`) once the runs are in.", block)
    (R / "RESULTS.md").write_text(md)


if __name__ == "__main__":
    main()
